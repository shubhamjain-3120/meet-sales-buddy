import { test } from "node:test";
import assert from "node:assert/strict";
import { createService, sign, verify } from "../auth/service.js";
import { createTokenServer } from "../auth/server.js";
import { createStore } from "../auth/store.js";
import { localDatabase } from "../auth/local-database.js";

const secrets = { apiKey: "app.key:ably-secret", sessionSecret: "a".repeat(32), setupKey: "b".repeat(32) };
const meeting = "abc-defg-hij";
const decode = token => JSON.parse(Buffer.from(token.split(".")[1], "base64url"));
function fixture(context, overrides = {}) {
  const db = localDatabase();
  context.after(() => db.close());
  const config = { ...secrets, store: createStore(db), revoke: async () => {}, ...overrides };
  const service = createService(config);
  return { service, config, db };
}
async function join(service, owner, name = "Member") {
  const invite = await service.invite(owner.credential);
  return { invite, member: await service.join(name, invite.inviteCode) };
}
test("one room and membership survive time, service restart and repeated owner setup", async context => {
  let time = 1_800_000_000_000;
  const { service, config } = fixture(context, { now: () => time });
  const owner = await service.create("Alex", secrets.setupKey);
  const invite = await service.invite(owner.credential);
  time += 10 * 365 * 86400 * 1000;
  const member = await service.join("Alex", invite.inviteCode);
  const second = (await join(service, owner)).member;
  assert.equal(member.room, owner.room);
  assert.equal(second.room, owner.room);
  assert.notEqual(member.clientId, second.clientId);
  assert.notEqual(member.clientId, owner.clientId);
  const restarted = createService(config);
  assert.deepEqual(await restarted.create("Other name", secrets.setupKey), owner);
  assert.deepEqual(await restarted.profile(member.credential), member);
  assert.equal(decode(member.credential).exp, undefined);
  assert.equal((await service.dashboard(owner.credential)).members.length, 3);
  await assert.rejects(service.join("Reuser", invite.inviteCode), /used or revoked/);
});
test("Ably tokens renew automatically and are scoped to the member and current Meet call", async context => {
  const { service } = fixture(context);
  const owner = await service.create("Owner", secrets.setupKey);
  const { member } = await join(service, owner);
  const token = await service.token(member.credential, meeting);
  const data = decode(token);
  assert.equal(data["x-ably-clientId"], member.clientId);
  assert.equal(data.exp - data.iat, 3600);
  assert.deepEqual(JSON.parse(data["x-ably-capability"]), { [`sales-buddy:${member.room}:${meeting}`]: ["publish", "subscribe", "presence", "history"] });
  assert.equal(sign(data, "ably-secret", { kid: "app.key" }), token);
  assert.notEqual(decode(await service.token(member.credential, "xyz-abcd-efg"))["x-ably-capability"], data["x-ably-capability"]);
  await assert.rejects(service.token(member.credential, ""), /Meet call/);
  await assert.rejects(service.token(member.credential, "abc-defg-hij:other"), /Meet call/);
});
test("single-use invites have one winner under concurrent redemption and only hashes are stored", async context => {
  const { service, db } = fixture(context);
  const owner = await service.create("Owner", secrets.setupKey);
  const invite = await service.invite(owner.credential);
  const results = await Promise.allSettled([service.join("A", invite.inviteCode), service.join("B", invite.inviteCode)]);
  assert.equal(results.filter(result => result.status === "fulfilled").length, 1);
  assert.equal((await service.dashboard(owner.credential)).members.length, 2);
  const saved = await db.prepare("SELECT * FROM invites").bind().first();
  assert.notEqual(saved.code_hash, invite.inviteCode);
  assert.equal(saved.code_hash.length, 64);
  assert.ok(saved.used_by);
});
test("only the owner manages invites and members; invite revocation doesn't remove joined members", async context => {
  const { service } = fixture(context);
  const owner = await service.create("Owner", secrets.setupKey);
  const unused = await service.invite(owner.credential);
  await service.revokeInvite(owner.credential, unused.id);
  await assert.rejects(service.join("Guest", unused.inviteCode), /used or revoked/);
  const { member, invite } = await join(service, owner);
  await assert.rejects(service.revokeInvite(owner.credential, invite.id), /already used/);
  await assert.rejects(service.invite(member.credential), /Only the owner/);
  await assert.rejects(service.remove(member.credential, owner.clientId.split(":")[1]), /Only the owner/);
  await assert.rejects(service.remove(owner.credential, owner.clientId.split(":")[1]), /owner/);
  assert.deepEqual(await service.dashboard(member.credential), { members: [], invites: [] });
  assert.equal((await service.profile(member.credential)).clientId, member.clientId);
});
test("member removal persists before live revocation, reports failure, and supports retry", async context => {
  let fail = true;
  const revoked = [];
  const { service, config } = fixture(context, { revoke: async id => { revoked.push(id); if (fail) throw new Error("Unavailable"); } });
  const owner = await service.create("Owner", secrets.setupKey);
  const { member } = await join(service, owner);
  const memberId = member.clientId.split(":")[1];
  assert.deepEqual(await service.remove(owner.credential, memberId), { removed: true, pending: true });
  await assert.rejects(createService(config).token(member.credential, meeting), /access was removed/);
  await assert.rejects(service.profile(member.credential), /access was removed/);
  assert.equal((await service.dashboard(owner.credential)).members.find(row => row.id === memberId).removal_pending, 1);
  fail = false;
  assert.deepEqual(await service.remove(owner.credential, memberId), { removed: true, pending: false });
  assert.deepEqual(revoked, [member.clientId, member.clientId]);
  const replacement = (await join(service, owner)).member;
  assert.notEqual(replacement.clientId, member.clientId);
});
test("forgeries, bad setup keys and credential substitution are rejected", async context => {
  const { service } = fixture(context);
  await assert.rejects(service.create("Owner", "wrong"), /setup key/);
  await assert.rejects(service.create(" ", secrets.setupKey), /name/);
  const owner = await service.create("Owner", secrets.setupKey);
  const invite = await service.invite(owner.credential);
  await assert.rejects(service.token(invite.inviteCode, meeting), /Invalid membership/);
  await assert.rejects(service.join("Member", owner.credential), /Invalid invite/);
  const forgery = owner.credential.split(".");
  forgery[1] = Buffer.from(JSON.stringify({ ...decode(owner.credential), id: "f".repeat(32) })).toString("base64url");
  await assert.rejects(service.profile(forgery.join(".")), /Invalid membership/);
  assert.throws(() => verify(owner.credential, "different-secret"), /Invalid credential/);
});
test("existing pairing upgrades once, preserves its room, and revoked legacy credentials stay denied", async context => {
  const { service } = fixture(context);
  const room = "c".repeat(32);
  const legacy = role => sign({ type: "member", room, role, name: role }, secrets.sessionSecret);
  await assert.rejects(service.profile(legacy("guest")), /owner's settings first/);
  const owner = await service.profile(legacy("host"));
  const member = await service.profile(legacy("guest"));
  assert.equal(owner.room, room);
  assert.equal(owner.role, "owner");
  assert.deepEqual(await service.create("Other", secrets.setupKey), owner);
  assert.deepEqual(await service.profile(legacy("guest")), member);
  await service.remove(owner.credential, member.clientId.split(":")[1]);
  await assert.rejects(service.profile(legacy("guest")), /access was removed/);
  const other = sign({ type: "member", room: "d".repeat(32), role: "host", name: "Other" }, secrets.sessionSecret);
  await assert.rejects(service.profile(other), /another old pairing/);
});
test("HTTP endpoints enforce access and return clean request and database failures", async context => {
  const { config } = fixture(context);
  const server = createTokenServer(config);
  await new Promise(resolve => server.listen(0, "127.0.0.1", resolve));
  context.after(() => new Promise(resolve => server.close(resolve)));
  const base = `http://127.0.0.1:${server.address().port}`;
  const post = (route, body, bearer) => fetch(base + route, { method: "POST", headers: { "Content-Type": "application/json", ...(bearer ? { Authorization: `Bearer ${bearer}` } : {}) }, body: JSON.stringify(body) });
  assert.equal((await post("/session", { name: "Owner" })).status, 400);
  const owner = await (await post("/session", { name: "Owner" }, secrets.setupKey)).json();
  const invite = await (await post("/invite", {}, owner.credential)).json();
  const member = await (await post("/join", { name: "Member", inviteCode: invite.inviteCode })).json();
  const token = await post("/token", { meeting }, member.credential);
  assert.equal(token.status, 200);
  assert.equal(token.headers.get("cache-control"), "no-store");
  assert.equal(decode(await token.text())["x-ably-clientId"], member.clientId);
  assert.equal((await post("/invite", {}, member.credential)).status, 403);
  assert.equal((await post("/token", { meeting }, "wrong")).status, 401);
  assert.equal((await post("/join", null)).status, 400);
  assert.equal((await post("/join", [])).status, 400);
  assert.equal((await fetch(base + "/token")).status, 404);
  assert.equal((await fetch(base + "/join", { method: "POST", body: "x".repeat(9000) })).status, 413);
  const original = config.store.room;
  config.store.room = async () => { throw new Error("SQL private details"); };
  const failure = await post("/session", { name: "Owner" }, secrets.setupKey);
  assert.equal(failure.status, 503);
  assert.deepEqual(await failure.json(), { error: "Service unavailable. Retry." });
  config.store.room = original;
});
